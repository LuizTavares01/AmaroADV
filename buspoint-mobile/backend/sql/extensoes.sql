-- Ponto de embarque do aluno em cada matrícula
ALTER TABLE matricula
    ADD COLUMN id_ponto_embarque BIGINT
        REFERENCES ponto_parada(id_ponto) ON DELETE SET NULL;

-- Motorista e ônibus padrão de cada rota (telas "Vincular motorista/ônibus")
CREATE TABLE rota_atribuicao (
    id_rota BIGINT PRIMARY KEY REFERENCES rota(id_rota) ON DELETE CASCADE,
    id_motorista BIGINT REFERENCES motorista(id_usuario),
    id_onibus BIGINT REFERENCES onibus(id_onibus)
);

-- Solicitações de alteração de horário feitas pelos alunos
CREATE TABLE solicitacao_horario (
    id_solicitacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno BIGINT NOT NULL REFERENCES aluno(id_usuario) ON DELETE CASCADE,
    id_rota BIGINT REFERENCES rota(id_rota),
    horario_atual TIME NOT NULL,
    horario_desejado TIME NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_solicitacao_status CHECK (status IN ('PENDENTE', 'APROVADA', 'RECUSADA'))
);
