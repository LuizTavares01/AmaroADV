-- BusPoint - SQL completo do banco PostgreSQL / Supabase
-- Atualizado conforme a implementação atual do backend

CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_usuario VARCHAR(50) NOT NULL,
    email_usuario VARCHAR(100) NOT NULL UNIQUE,
    telefone_usuario VARCHAR(13) NOT NULL,
    login_usuario VARCHAR(40) NOT NULL UNIQUE,
    senha_usuario VARCHAR(150) NOT NULL,
    status_usuario BOOLEAN NOT NULL DEFAULT TRUE,
    foto_usuario TEXT
);

CREATE TABLE aluno (
    id_usuario BIGINT PRIMARY KEY,
    numero_matricula INTEGER NOT NULL UNIQUE,
    periodo VARCHAR(50) NOT NULL,
    status_matricula BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_aluno_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE
);

CREATE TABLE motorista (
    id_usuario BIGINT PRIMARY KEY,
    numero_cnh VARCHAR(20) NOT NULL UNIQUE,
    categoria_cnh VARCHAR(10) NOT NULL,
    validade_cnh DATE NOT NULL,
    CONSTRAINT fk_motorista_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE
);

CREATE TABLE administrador (
    id_usuario BIGINT PRIMARY KEY,
    CONSTRAINT fk_administrador_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE
);

CREATE TABLE ponto_parada (
    id_ponto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_ponto VARCHAR(100) NOT NULL,
    endereco VARCHAR(255) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL
);

CREATE TABLE rota (
    id_rota BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_rota VARCHAR(100) NOT NULL,
    horario_inicio TIME NOT NULL,
    horario_fim TIME NOT NULL,
    status_rota BOOLEAN NOT NULL DEFAULT TRUE,
    tipo VARCHAR(50) NOT NULL
);

CREATE TABLE rota_ponto_parada (
    id_rota BIGINT NOT NULL,
    id_ponto BIGINT NOT NULL,
    ordem INTEGER NOT NULL,
    PRIMARY KEY (id_rota, id_ponto),
    CONSTRAINT fk_rota_ponto_rota
        FOREIGN KEY (id_rota)
        REFERENCES rota(id_rota)
        ON DELETE CASCADE,
    CONSTRAINT fk_rota_ponto_ponto
        FOREIGN KEY (id_ponto)
        REFERENCES ponto_parada(id_ponto)
        ON DELETE CASCADE,
    CONSTRAINT uk_rota_ponto_ordem
        UNIQUE (id_rota, ordem),
    CONSTRAINT ck_rota_ponto_ordem
        CHECK (ordem >= 1)
);

CREATE TABLE onibus (
    id_onibus BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa_onibus VARCHAR(10) NOT NULL UNIQUE,
    capacidade_onibus INTEGER NOT NULL,
    status_onibus BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_onibus_capacidade
        CHECK (capacidade_onibus > 0)
);

CREATE TABLE viagem (
    id_viagem BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_viagem DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fim TIME,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    observacao_finalizacao VARCHAR(255),
    id_rota BIGINT NOT NULL,
    id_motorista BIGINT NOT NULL,
    id_onibus BIGINT NOT NULL,
    CONSTRAINT fk_viagem_rota
        FOREIGN KEY (id_rota)
        REFERENCES rota(id_rota),
    CONSTRAINT fk_viagem_motorista
        FOREIGN KEY (id_motorista)
        REFERENCES motorista(id_usuario),
    CONSTRAINT fk_viagem_onibus
        FOREIGN KEY (id_onibus)
        REFERENCES onibus(id_onibus),
    CONSTRAINT ck_viagem_status
        CHECK (status IN ('PENDENTE', 'EM_ANDAMENTO', 'FINALIZADA'))
);

CREATE TABLE matricula (
    id_matricula BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno BIGINT NOT NULL,
    id_rota BIGINT NOT NULL,
    status_matricula BOOLEAN NOT NULL DEFAULT TRUE,
    data_matricula DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT fk_matricula_aluno
        FOREIGN KEY (id_aluno)
        REFERENCES aluno(id_usuario)
        ON DELETE CASCADE,
    CONSTRAINT fk_matricula_rota
        FOREIGN KEY (id_rota)
        REFERENCES rota(id_rota),
    CONSTRAINT uk_matricula_aluno_rota
        UNIQUE (id_aluno, id_rota)
);

CREATE TABLE registro_transporte (
    id_aluno BIGINT NOT NULL,
    id_viagem BIGINT NOT NULL,
    tipo_registro VARCHAR(30) NOT NULL,
    data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    justificativa VARCHAR(255),
    status BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id_aluno, id_viagem, tipo_registro),
    CONSTRAINT fk_registro_aluno
        FOREIGN KEY (id_aluno)
        REFERENCES aluno(id_usuario)
        ON DELETE CASCADE,
    CONSTRAINT fk_registro_viagem
        FOREIGN KEY (id_viagem)
        REFERENCES viagem(id_viagem)
        ON DELETE CASCADE,
    CONSTRAINT ck_registro_tipo
        CHECK (tipo_registro IN ('EMBARQUE', 'DESEMBARQUE'))
);

-- Índices para consultas usadas pelo backend
CREATE INDEX idx_matricula_aluno
    ON matricula(id_aluno);

CREATE INDEX idx_matricula_rota
    ON matricula(id_rota);

CREATE INDEX idx_viagem_rota
    ON viagem(id_rota);

CREATE INDEX idx_viagem_motorista
    ON viagem(id_motorista);

CREATE INDEX idx_viagem_onibus
    ON viagem(id_onibus);

CREATE INDEX idx_registro_viagem
    ON registro_transporte(id_viagem);

CREATE INDEX idx_registro_aluno
    ON registro_transporte(id_aluno);
