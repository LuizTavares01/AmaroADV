/* Banco de dados do BusPoint.
   Mantém as mesmas tabelas do script BusPoint-banco.sql (PostgreSQL), em memória,
   com persistência plugável (AsyncStorage no app, arquivo JSON no servidor Node).
   As operações de escrita rodam em "transações": se algo falhar, o estado anterior volta. */
import { criarDadosIniciais } from './seed.js';

export const TABELAS = [
  'usuario', 'aluno', 'motorista', 'administrador',
  'ponto_parada', 'rota', 'rota_ponto_parada', 'onibus',
  'viagem', 'matricula', 'registro_transporte',
  // extensões (ver backend/sql/extensoes.sql)
  'rota_atribuicao', 'solicitacao_horario',
];

const VERSAO = 1;

export class Database {
  /** @param {{ load: () => Promise<string|null>, save: (json: string) => Promise<void> }} adapter */
  constructor(adapter) {
    this.adapter = adapter;
    this.data = null;
    this.fila = Promise.resolve();
  }

  async init() {
    let raw = null;
    try { raw = await this.adapter.load(); } catch { raw = null; }
    if (raw) {
      try {
        const parsed = JSON.parse(raw);
        if (parsed && parsed.versao === VERSAO && parsed.tabelas) this.data = parsed;
      } catch { this.data = null; }
    }
    if (!this.data) {
      this.data = criarDadosIniciais(VERSAO);
      await this.persistir();
    }
    for (const t of TABELAS) if (!this.data.tabelas[t]) this.data.tabelas[t] = [];
    if (!this.data.sessoes) this.data.sessoes = {};
    if (!this.data.redefinicoes) this.data.redefinicoes = {};
    return this;
  }

  async restaurar() {
    this.data = criarDadosIniciais(VERSAO);
    await this.persistir();
  }

  async persistir() {
    await this.adapter.save(JSON.stringify(this.data));
  }

  tabela(nome) {
    return this.data.tabelas[nome];
  }

  // GENERATED BY DEFAULT AS IDENTITY
  proximoId(tabela) {
    const seq = this.data.sequencias;
    seq[tabela] = (seq[tabela] || 0) + 1;
    return seq[tabela];
  }

  /** Executa fn de forma serializada; desfaz alterações se ocorrer erro (@Transactional). */
  transacao(fn) {
    const exec = async () => {
      const copia = JSON.stringify(this.data);
      try {
        const r = await fn();
        await this.persistir();
        return r;
      } catch (e) {
        this.data = JSON.parse(copia);
        throw e;
      }
    };
    const p = this.fila.then(exec, exec);
    this.fila = p.catch(() => {});
    return p;
  }
}
